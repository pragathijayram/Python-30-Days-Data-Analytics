# Day 4: Python Operators

# 1. Arithmetic Operators
sales_month1 = 45000
sales_month2 = 50000
total_sales = sales_month1 + sales_month2
print("Total Sales:", total_sales)

# 2. Comparison Operators
target = 90000
is_target_achieved = total_sales >= target
print("Is sales target achieved?", is_target_achieved)

# 3. Logical Operators
high_sales = total_sales > 80000
profitable = True
print("Is business booming (Both conditions)?", high_sales and profitable)