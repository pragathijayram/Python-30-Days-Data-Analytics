# Day 3: Python Data Types
# 1. Integer (int)
store_id = 101
print("store ID type:",
      type(store_id))
# 2. Float (float)
profit_margin = 18.5
print("Profit Margin type:",
      type(profit_margin))
# 3. String (str)
item_name = "office Supplies"
print("Item Name type:",
      type(item_name))
# 4. Boolean (bool)
is_in_stock = True
print("Is in stock type:",
      type(is_in_stock))