# Day 11: Python For Loop

print("--- 1. Printing numbers from 1 to 5 using range() ---")
for i in range(1, 6):
    print("Current Number:", i)

print("\n--- 2. Looping through a list of store items ---")
items = ["Laptops", "Printers", "Office Supplies", "Desks"]

for item in items:
    print("Available Item:", item)